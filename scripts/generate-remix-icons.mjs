function resolveRemixKey(raw) {
  if (remixKeys.has(raw)) return raw;
  const alts = [
    raw.replace(/Line$/, 'Fill'),
    raw.replace(/Fill$/, 'Line'),
    `${raw}Line`,
    `${raw}Fill`,
  ];
  for (const key of alts) {
    if (remixKeys.has(key)) return key;
  }
  return null;
}

const iconFileTemplate = (name, remixKey) => `/** @generated — Remix Icon (${remixKey}) */
import { ${remixKey} } from '@remixicon/react';
import { createRemixIcon } from '../createRemixIcon';

export const ${name} = createRemixIcon(${remixKey}, '${name}');
`;

const existingNames = readdirSync(iconsDir)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) => f.replace('.tsx', ''))
  .sort();

const missingMap = [];
const invalidRemix = [];

for (const name of existingNames) {
  const raw = REMIX_ICON_MAP[name];
  if (!raw) {
    missingMap.push(name);
    continue;
  }
  const remixKey = resolveRemixKey(raw);
  if (!remixKey) {
    invalidRemix.push({ name, raw });
    continue;
  }
  REMIX_ICON_MAP[name] = remixKey;
  writeFileSync(join(iconsDir, `${name}.tsx`), iconFileTemplate(name, remixKey), 'utf8');
}

if (missingMap.length || invalidRemix.length) {
  console.error('Generation failed:', { missingMap, invalidRemix });
  process.exit(1);
}

const names = existingNames;
const indexLines = [
  '/** @generated — do not edit by hand; run `node scripts/generate-remix-icons.mjs` */',
  ...names.map((n) => `export { ${n} } from './icons/${n}';`),
  "/** Renamed from `Drawer` to avoid clashing with `Drawer` (slide-in panel) on the package root. */",
  "export { Drawer as DrawerIcon } from './icons/Drawer';",
  "export { Icon } from './Icon';",
  "export type { IconName } from './iconNames';",
  "export { iconCategories, type IconCategory } from './categories';",
];
writeFileSync(join(root, 'src/icons/index.ts'), `${indexLines.join('\n')}\n`, 'utf8');

const iconNameUnion = names.map((n) => `'${n}'`).join(' | ');
writeFileSync(
  join(root, 'src/icons/iconNames.ts'),
  `/** @generated */\nexport type IconName = ${iconNameUnion};\n\nexport const iconNames = [\n${names.map((n) => `  '${n}',`).join('\n')}\n] as const satisfies readonly IconName[];\n`,
  'utf8',
);

const iconTsxLines = [
  '/** @generated — dynamic Icon wrapper */',
  "import React, { lazy, Suspense, type FC } from 'react';",
  "import type { IconName } from './iconNames';",
  "import type { CaterIconProps } from './createRemixIcon';",
  '',
  'const iconComponents: Record<',
  '  IconName,',
  '  React.LazyExoticComponent<FC<CaterIconProps>>',
  '> = {',
  ...names.map(
    (n) =>
      `  ${n}: lazy(() => import('./icons/${n}').then((m) => ({ default: m.${n} as FC<CaterIconProps> }))),`,
  ),
  '};',
  '',
  "export type { IconName } from './iconNames';",
  '',
  'export interface IconProps extends CaterIconProps {',
  '  name: IconName;',
  '}',
  '',
  'export const Icon: FC<IconProps> = ({ name, size = 24, width, height, ...props }) => {',
  '  const LazyIcon = iconComponents[name];',
  '  if (!LazyIcon) return null;',
  '  const resolvedWidth = width ?? size;',
  '  const resolvedHeight = height ?? size;',
  '  return (',
  '    <Suspense fallback={<svg width={resolvedWidth} height={resolvedHeight} aria-hidden />}>',
  '      <LazyIcon width={resolvedWidth} height={resolvedHeight} size={size} {...props} />',
  '    </Suspense>',
  '  );',
  '};',
];
writeFileSync(join(root, 'src/icons/Icon.tsx'), `${iconTsxLines.join('\n')}\n`, 'utf8');

writeFileSync(
  join(root, 'scripts/remix-icon-map.json'),
  JSON.stringify(REMIX_ICON_MAP, null, 2),
  'utf8',
);

console.log(`Generated ${names.length} Remix icon wrappers.`);
